import esbuild from "esbuild";
import fs from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { createRequire } from "node:module";
import { createHash } from "node:crypto";

const directory = path.dirname(fileURLToPath(import.meta.url));
const result = await esbuild.build({
  entryPoints: [path.join(directory, "runtime/entry.ts")],
  bundle: true,
  write: false,
  format: "iife",
  platform: "browser",
  target: "chrome110",
  minify: true,
  legalComments: "inline",
});
const script = result.outputFiles[0].text.replace(/<\/script/gi, "<\\/script");
const require = createRequire(import.meta.url);
const pdfRoot = path.dirname(require.resolve("pdfjs-dist/package.json"));
const resources = {};
const notices = [];
for (const folder of ["cmaps", "standard_fonts", "wasm"]) {
  for (const name of await fs.readdir(path.join(pdfRoot, folder))) {
    if (/^LICENSE/i.test(name))
      notices.push(await fs.readFile(path.join(pdfRoot, folder, name), "utf8"));
    if (!/\.(?:bcmap|pfb|ttf|wasm)$/.test(name)) continue;
    resources[name] = (await fs.readFile(path.join(pdfRoot, folder, name))).toString("base64");
  }
}
const digestMarker = "PASEO_DOCUMENT_RUNTIME_SHA256";
const template = `<!doctype html><html><head><meta charset="utf-8"><meta name="paseo-document-runtime" content="${digestMarker}">
<meta http-equiv="Content-Security-Policy" content="default-src 'none'; script-src 'unsafe-inline' 'wasm-unsafe-eval'; style-src 'unsafe-inline'; img-src data: blob:; font-src data: blob:; connect-src 'none'; worker-src 'none'; object-src 'none'; frame-src 'none'; base-uri 'none'; form-action 'none'">
<meta name="viewport" content="width=device-width, initial-scale=1">
<style>
*{box-sizing:border-box}html,body{margin:0;height:100%;font:15px system-ui,sans-serif;background:#f3f4f6;color:#202124}
body{display:flex;flex-direction:column}#controls{display:flex;align-items:center;gap:8px;padding:8px;flex-wrap:wrap;background:#fff;border-bottom:1px solid #ddd;flex-shrink:0}
#controls:empty{display:none}button,select{font:inherit;border:1px solid #ddd;border-radius:6px;padding:6px 10px;background:white;color:#202124;min-height:32px}button:disabled{opacity:.4}button:not(:disabled){cursor:pointer}
#content{flex:1;min-height:0;overflow:auto;padding:12px;overscroll-behavior:contain}pre{white-space:pre-wrap;overflow-wrap:anywhere;font:14px/1.6 ui-monospace,monospace;user-select:text}
table{border-collapse:collapse;background:white;font-size:14px}th,td{border:1px solid #ddd;padding:6px 10px;min-width:80px;max-width:400px;white-space:pre-wrap;overflow-wrap:anywhere}th{background:#eee;position:sticky;top:0;font-weight:500}tr>th:first-child{min-width:40px;left:0}
canvas{display:block;background:white;max-width:none;margin:0 auto}svg{display:block;height:auto;background:white}.pdf-text{white-space:pre-wrap;max-width:900px;margin:16px auto;line-height:1.6;user-select:text}
.docx-wrapper{padding:0!important;background:transparent!important;align-items:flex-start!important}.docx-wrapper>section.docx{margin-bottom:12px!important;box-shadow:0 1px 4px #0002!important}
</style></head><body><nav id="controls"></nav><main id="content"></main>
<script type="text/plain" id="third-party-notices">${notices.join("\n\n").replace(/<\/script/gi, "<\\/script")}</script><script>/*PASEO_DOCUMENT_REQUEST*/</script><script>window.__paseoPdfResources=${JSON.stringify(resources)};</script><script>${script}</script></body></html>`;
const digest = createHash("sha256").update(template).digest("hex");
const html = template.replace(digestMarker, digest);
await fs.writeFile(
  path.join(directory, "runtime/html.gen.ts"),
  `// Generated by file-pane/document-preview/build-runtime.mjs.\nexport const documentRuntimeHtml = ${JSON.stringify(html)};\n`,
);
console.log(`Document preview runtime: ${(html.length / 1024 / 1024).toFixed(2)} MB`);
console.log(`Runtime SHA-256: ${digest}`);

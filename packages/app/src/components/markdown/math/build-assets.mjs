import fs from "node:fs/promises";
import path from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const directory = path.dirname(fileURLToPath(import.meta.url));
const require = createRequire(import.meta.url);
const stylesheet = require.resolve("katex/dist/katex.min.css");
const css = await fs.readFile(stylesheet, "utf8");
// Native WebViews load from about:blank. Inline WOFF2 avoids both CDN access and file URLs.
const fontFaces = /@font-face\{[^}]+\}/g;
let bundledCss = css;
for (const match of css.matchAll(fontFaces)) {
  const font = match[0].match(/url\(([^)]+\.woff2)\)/)[1];
  const data = await fs.readFile(path.resolve(path.dirname(stylesheet), font));
  const face = match[0].replace(
    /src:[^}]+/,
    `src:url(data:font/woff2;base64,${data.toString("base64")}) format("woff2")`,
  );
  bundledCss = bundledCss.replace(match[0], face);
}
await fs.writeFile(
  path.join(directory, "assets.gen.ts"),
  `// Generated by build-assets.mjs. KaTeX and its fonts are MIT licensed.\nexport const mathCss = ${JSON.stringify(bundledCss)};\n`,
);
await fs.writeFile(
  path.join(directory, "katex.gen.css"),
  `/* Generated by build-assets.mjs. KaTeX and its fonts are MIT licensed. */\n${bundledCss}\n`,
);
console.log(`Bundled offline math styles and fonts (${bundledCss.length} bytes)`);
